#!/usr/bin/env node

/**
 * Writes src/app/member-hash.generated.ts before the app is built, served or tested.
 *
 * The bcrypt hash comes from the MEMBER_PASSWORD_HASH environment variable or the
 * git-ignored .member-password-hash file (see scripts/generate-hash-parts.js).
 * With neither, the generated hash is empty and every login attempt fails.
 */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const hashFile = path.join(root, '.member-password-hash');
const outFile = path.join(root, 'src', 'app', 'member-hash.generated.ts');

const hash = (
  process.env.MEMBER_PASSWORD_HASH ||
  (fs.existsSync(hashFile) ? fs.readFileSync(hashFile, 'utf8') : '')
).trim();

if (!hash) {
  console.warn('WARNING: no member password hash found, so the members login will reject every password.');
  console.warn('         Run: node scripts/generate-hash-parts.js');
}

// Split into 3 Base64 parts, matching the obfuscation AuthService has always used
const size = Math.floor(hash.length / 3);
const parts = [hash.slice(0, size), hash.slice(size, size * 2), hash.slice(size * 2)]
  .map(part => Buffer.from(part).toString('base64'));

fs.writeFileSync(
  outFile,
  '// Generated by scripts/write-member-hash.js. Do not edit or commit.\n' +
  `export const MEMBER_HASH_PARTS: string[] = ${JSON.stringify(parts)};\n`
);
